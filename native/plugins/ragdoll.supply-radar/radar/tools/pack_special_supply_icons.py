"""Pack the generated transparent sprite sheet into the HUD's RGBA texture header."""

from pathlib import Path

from PIL import Image


ROOT = Path(__file__).resolve().parents[1]
# The palette controls each row's arrow and its default in-world glow.
SPRITES = (
    ("cola", (244, 103, 113)),
    ("gnome", (248, 225, 185)),
    ("explosive", (251, 208, 104)),
    ("incendiary", (252, 134, 76)),
)


def main():
    sheet = Image.open(ROOT / "assets" / "supply-radar-icons.png").convert("RGBA")
    width, height = sheet.size
    header = ['#pragma once', '#include "classic_hud_artwork.h"',
              '// Generated by tools/pack_special_supply_icons.py.',
              'namespace special_supply_artwork {']
    metadata = []
    for index, (name, palette) in enumerate(SPRITES):
        x, y = index % 2, index // 2
        cell = sheet.crop((x * width // 2, y * height // 2,
                           (x + 1) * width // 2, (y + 1) * height // 2))
        # Ignore faint distant pixels when finding the crop, then preserve
        # the original alpha at the edges of the isolated asset.
        bounds = cell.getchannel("A").point([0] * 16 + [255] * 240).getbbox()
        if bounds is None:
            raise ValueError(f"Empty sprite: {name}")
        l, t, r, b = bounds
        icon = cell.crop((max(l - 2, 0), max(t - 2, 0),
                          min(r + 2, cell.width), min(b + 2, cell.height)))
        icon.thumbnail((56, 56), Image.Resampling.LANCZOS)
        raw = icon.tobytes()
        header.append(f'static constexpr unsigned char {name}[]={{')
        for at in range(0, len(raw), 24):
            header.append('    ' + ','.join(map(str, raw[at:at + 24])) + ',')
        header.append('};')
        metadata.append((icon.width, icon.height, *palette))

    header.append('static constexpr classic_hud_artwork::Meta meta[]={')
    header.extend('    {' + ','.join(map(str, m)) + '},' for m in metadata)
    header.extend(['};', 'constexpr unsigned Count=sizeof(meta)/sizeof(meta[0]);',
                   'static constexpr const unsigned char* rgba[Count]={' +
                   ','.join(name for name, _ in SPRITES) + '};', '}', ''])
    (ROOT / "special_supply_artwork.h").write_text('\n'.join(header), encoding='ascii')


if __name__ == "__main__":
    main()
