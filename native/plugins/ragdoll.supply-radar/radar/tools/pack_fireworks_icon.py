"""Embed the circular fireworks badge supplied as assets/fireworks.jpg."""

from pathlib import Path

from PIL import Image, ImageDraw


ROOT = Path(__file__).resolve().parents[1]
SIZE = 56


def main():
    with Image.open(ROOT / 'assets' / 'fireworks.jpg') as source:
        badge = source.convert('RGBA')

    # The blue disc is part of the badge. Trim two source pixels at its rim
    # to keep the flattened checkerboard and JPEG fringe outside the mask.
    w, h = badge.size
    mask = Image.new('L', (w * 4, h * 4))
    ImageDraw.Draw(mask).ellipse((8, 8, w * 4 - 9, h * 4 - 9), fill=255)
    badge.putalpha(mask.resize(badge.size, Image.Resampling.BOX))
    badge = badge.resize((SIZE, SIZE), Image.Resampling.LANCZOS)
    raw = badge.tobytes()

    header = ['#pragma once', '// Generated by tools/pack_fireworks_icon.py.',
              'namespace fireworks_artwork {', f'constexpr unsigned Size={SIZE};',
              'static constexpr unsigned char rgba[]={']
    header += ['    ' + ','.join(map(str, raw[i:i + 24])) + ',' for i in range(0, len(raw), 24)]
    header += ['};', 'static_assert(sizeof(rgba)==Size*Size*4,"Fireworks texture size");', '}', '']
    (ROOT / 'fireworks_artwork.h').write_text('\n'.join(header), encoding='ascii')


if __name__ == '__main__':
    main()
