import fs from 'node:fs/promises';
import path from 'node:path';
import { createServer } from 'vite';
import { svelte } from '@sveltejs/vite-plugin-svelte';
import { createPlatform } from '../backend/core.mjs';
import { createFixture } from '../backend/tests/fixtures.mjs';
import { ServerManager } from '../backend/servers/manager.mjs';
import { emptyObservation } from '../backend/servers/query.mjs';
import { beaconBridge } from '../backend/desktop/vite-plugin.mjs';
const project = path.resolve(import.meta.dirname, '..');
const base = await fs.mkdtemp(path.join(project, 'checks/.artifacts/launch-ui-'));
const fixture = await createFixture(base);
const core = createPlatform({ getProcesses: async () => [], launchGame: async () => { throw new Error('Offline UI fixture: game launch is disabled'); } });
await core.applyInstall(await core.planInstall(fixture), { confirmation: { approved: true, source: 'user' } });
core.discover = async () => ({ games: [await core.inspectGame(fixture.gameRoot)], warnings: [] });
const dataDir = path.join(base, 'settings');
const manager = new ServerManager({ dataDir });
await manager.add({ address: '127.0.0.1:27015' });
await manager.close();
const queryServer = async () => ({ ...emptyObservation(), name: '离线界面夹具 · VAC', status: 'online', mode: '战役', modeId: 'coop', map: 'c2m1_highway', players: 0, maxPlayers: 8, ping: 34, vac: true, password: false, checkedAt: new Date().toISOString(), connectAddr: '127.0.0.1:27015' });
const server = await createServer({ root: project, configFile: false, cacheDir: path.join(base, 'vite-cache'), plugins: [svelte(), beaconBridge({ core, dataDir, queryServer })], server: { host: '127.0.0.1', port: 5176, strictPort: true }, clearScreen: false });
await server.listen();
console.log(JSON.stringify({ url: 'http://127.0.0.1:5176', dataDir, gameRoot: fixture.gameRoot, gameLaunchDisabled: true }));
await new Promise(resolve => { process.stdin.once('data', resolve); process.stdin.once('end', resolve); process.once('SIGINT', resolve); });
process.stdin.pause();
await server.close();
