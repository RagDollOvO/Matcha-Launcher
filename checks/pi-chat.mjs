import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
import ts from 'typescript';
import { compileModule } from 'svelte/compiler';

const source = await fs.readFile(new URL('../src/lib/agent/chat.svelte.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const output = compileModule(js, { filename: 'chat.svelte.js', generate: 'client' }).js.code;
const file = path.resolve('checks/.artifacts/pi-chat-compiled.mjs');
await fs.mkdir(path.dirname(file), { recursive: true });
await fs.writeFile(file, output);
const { Chat } = await import(pathToFileURL(file));
let emit; const sent = [];
const chat = new Chat({ subscribe: listener => { emit = listener; return () => {}; }, send: c => sent.push(c) });
emit({ type: 'connection', status: 'connected' });
emit({ type: 'response', command: 'get_state', success: true, data: { model: { id: 'fixture-model' }, isStreaming: false } });
assert.equal(chat.model, 'fixture-model');
emit({ type: 'message_start', message: { role: 'user', content: [{ type: 'text', text: '检查幸存者' }] } });
assert.equal(chat.messages[0].text, '检查幸存者');
emit({ type: 'message_start', message: { role: 'assistant', content: [] } });
const call = { type: 'toolCall', id: 'read-1', name: 'platform_inspect', arguments: {} };
emit({ type: 'message_update', assistantMessageEvent: { type: 'toolcall_start', contentIndex: 0, partial: { role: 'assistant', content: [call] } } });
emit({ type: 'message_end', message: { role: 'assistant', content: [call] } });
emit({ type: 'tool_execution_start', toolCallId: 'read-1', toolName: 'platform_inspect', args: {} });
emit({ type: 'message_start', message: { role: 'toolResult', content: [] } });
emit({ type: 'message_end', message: { role: 'toolResult', toolCallId: 'read-1', content: [{ type: 'text', text: '真实结果' }] } });
assert.equal(chat.messages.length, 2);
assert.equal(chat.messages[1].blocks[0].output, '真实结果');
emit({ type: 'message_start', message: { role: 'assistant', content: [] } });
emit({ type: 'message_update', assistantMessageEvent: { type: 'text_delta', contentIndex: 0, delta: '部分文本' } });
emit({ type: 'message_end', message: { role: 'assistant', content: [{ type: 'text', text: '最终完整文本' }] } });
assert.equal(chat.messages[2].blocks[0].text, '最终完整文本');
emit({ type: 'extension_ui_request', id: 'approval-1', method: 'confirm', title: '确认动作', message: '没有运行中的工具卡时仍可批准' });
chat.respond('approval-1', true);
assert.equal(sent.at(-1).confirmed, true);
assert.equal(chat.dialogs[0].state, 'waiting');
emit({ type: 'response', id: 'approval-1', command: 'extension_ui_response', success: true });
assert.equal(chat.dialogs[0].state, 'allowed');
chat.reset();
assert.equal(chat.messages.length, 3);
emit({ type: 'response', command: 'new_session', success: false, error: 'fixture failure' });
assert.equal(chat.messages[0].text, '检查幸存者');
emit({ type: 'connection', status: 'disconnected' });
assert.equal(chat.running, false);
chat.dispose();
console.log('Pi chat: real-shaped messages, final reconciliation, standalone approval and failure retention passed.');
