import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import { execFile as callback } from 'node:child_process';
import { promisify } from 'node:util';
import { createPlatform } from '../backend/core.mjs';
import { verifyRelease } from '../backend/releases.mjs';
import { createFixture } from '../backend/tests/fixtures.mjs';
import extension from '../backend/pi/platform-extension.mjs';
const execFile=promisify(callback), base=path.resolve('checks/.artifacts');
const source=path.resolve(process.argv[2] ?? 'checks/.artifacts/beacon-demo-release-02');
const trust=path.resolve(process.argv[3] ?? 'checks/.artifacts/beacon-demo-trust-02.json');
const root=await fs.mkdtemp(path.join(base,'beacon-release-check-'));
const confirmation={approved:true,source:'user'}, results=[];
const api=createPlatform({getProcesses:async()=>[]});
const f=await createFixture(root);
// Keep the existing legacy fixture, disabled, and install the signed demo beside
// it. All writes are inside this script's newly allocated offline workspace.
const legacy=path.join(f.distRoot,'bin/l4p/plugins/demo.hello');
const m=JSON.parse(await fs.readFile(path.join(legacy,'manifest.json'),'utf8')); m.id='legacy.demo';
await fs.writeFile(path.join(legacy,'manifest.json'),JSON.stringify(m));
await fs.rename(legacy,path.join(path.dirname(legacy),'legacy.demo'));
await fs.writeFile(path.join(f.distRoot,'bin/l4p/enabled.txt'),'');
await fs.copyFile(path.resolve('native/build-x86/dist/bin/l4p/l4p_runtime.dll'),path.join(f.distRoot,'bin/l4p/l4p_runtime.dll'));
await api.applyInstall(await api.planInstall(f),{confirmation});
await api.configureReleaseTrust({gameRoot:f.gameRoot,policyPath:trust,confirmation});
const runtimeBytes=await fs.readFile(path.join(f.runtime,'l4p_runtime.dll'));
const { peFixture }=await import('../backend/tests/fixtures.mjs');
await fs.writeFile(path.join(f.runtime,'l4p_runtime.dll'),peFixture(['L4P_RuntimeInitialize']));
await assert.rejects(api.installPlugin({gameRoot:f.gameRoot,pluginDirectory:source,confirmation}),e=>e.code==='runtime_upgrade_required');
await fs.writeFile(path.join(f.runtime,'l4p_runtime.dll'),runtimeBytes);
results.push({case:'old-runtime-blocks-verified-install',ok:true});
const installed=await api.installPlugin({gameRoot:f.gameRoot,pluginDirectory:source,confirmation});
assert.equal(installed.verification.state,'verified-development');
await api.setPluginEnabled({gameRoot:f.gameRoot,pluginId:'demo.hello',enabled:true,confirmation});
assert.equal((await api.listPlugins(f.gameRoot)).find(p=>p.manifest.id==='legacy.demo').verification.state,'unverified');
results.push({case:'verified-install-and-legacy-state',ok:true});
const plugin=path.join(f.runtime,'plugins/demo.hello');
const run=async mode=>JSON.parse((await execFile(path.resolve('native/build-x86/fixtures/beacon_release_smoke.exe'),[f.runtime,mode],{windowsHide:true,timeout:15000})).stdout);
results.push({case:'runtime-hello-and-payload-lock',...(await run('allow'))});
const reject=async (name,edit,restore)=>{
  await edit();
  await assert.rejects(verifyRelease(plugin,path.join(f.runtime,'release-trust.json')));
  const result=await run('reject'); assert.equal(result.pluginMapped,false);
  results.push({case:name,...result}); await restore();
};
const bytes=await fs.readFile(path.join(plugin,'plugin.dll'));
await reject('dll-tamper-before-DllMain',()=>fs.appendFile(path.join(plugin,'plugin.dll'),'tampered'),()=>fs.writeFile(path.join(plugin,'plugin.dll'),bytes));
const metadata=await fs.readFile(path.join(plugin,'release.json'));
await reject('signed-metadata-tamper',()=>fs.appendFile(path.join(plugin,'release.json'),' '),()=>fs.writeFile(path.join(plugin,'release.json'),metadata));
const evidence=await fs.readFile(path.join(plugin,'build-evidence.json'));
await reject('other-payload-tamper',()=>fs.appendFile(path.join(plugin,'build-evidence.json'),' '),()=>fs.writeFile(path.join(plugin,'build-evidence.json'),evidence));
await reject('unlisted-executable-content',()=>fs.writeFile(path.join(plugin,'extra.ps1'),'exit 0'),()=>fs.unlink(path.join(plugin,'extra.ps1')));
const policy=await fs.readFile(path.join(f.runtime,'release-trust.json'));
await reject('untrusted-signer',async()=>{const p=JSON.parse(policy);p.signers=[];await fs.writeFile(path.join(f.runtime,'release-trust.json'),JSON.stringify(p));},()=>fs.writeFile(path.join(f.runtime,'release-trust.json'),policy));
await reject('revoked-release',async()=>{const p=JSON.parse(policy);p.revokedReleases=[installed.verification.releaseSha256];await fs.writeFile(path.join(f.runtime,'release-trust.json'),JSON.stringify(p));},()=>fs.writeFile(path.join(f.runtime,'release-trust.json'),policy));
const signature=await fs.readFile(path.join(plugin,'release.p7s'));
await reject('cms-signature-tamper',async()=>{const bytes=Buffer.from(signature);bytes[bytes.length-1]^=1;await fs.writeFile(path.join(plugin,'release.p7s'),bytes);},()=>fs.writeFile(path.join(plugin,'release.p7s'),signature));
await reject('stripped-release-downgrade',async()=>{await fs.unlink(path.join(plugin,'release.json'));await fs.unlink(path.join(plugin,'release.p7s'));},async()=>{await fs.writeFile(path.join(plugin,'release.json'),metadata);await fs.writeFile(path.join(plugin,'release.p7s'),signature);});
const registered=new Map();extension({registerTool:t=>registered.set(t.name,t)});
const tool=registered.get('plugin_project_check');
assert.equal((await tool.execute('cancel',{directory:path.resolve('native/examples/demo.hello')},null,null,{hasUI:true,ui:{confirm:async()=>false}})).details.applied,false);
const checked=await tool.execute('approved',{directory:path.resolve('native/examples/demo.hello')},null,null,{hasUI:true,ui:{confirm:async()=>true}});
assert.equal(checked.details.status,'ready-for-build'); results.push({case:'pi-scope-confirmation-and-rules',report:checked.details});
const report={schemaVersion:1,kind:'beacon-release-offline-check',root,results,gameExecuted:false};
await fs.writeFile(path.join(root,'report.json'),JSON.stringify(report,null,2));
console.log(JSON.stringify({report:path.join(root,'report.json'),cases:results.length,status:'passed'},null,2));
