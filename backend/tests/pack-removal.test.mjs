import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import os from 'node:os';
import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {createPlatform} from '../core.mjs';
import {DesktopService} from '../desktop/service.mjs';
import {dllHost} from '../pi/dll-host.mjs';
import {dllTools} from '../pi/dll-tools.mjs';
import {createFixture,peFixture} from './fixtures.mjs';
import {zip} from './platforms-fixtures.mjs';

test('uninstall from chat: stale card, parked entry, updater and game selection; keep foreign files',async t=>{
  const base=await fs.mkdtemp(path.join(os.tmpdir(),'matcha-remove-'));
  const {gameRoot:root,distRoot}=await createFixture(base);
  const put=async(r,b)=>{const f=path.join(root,r);await fs.mkdir(path.dirname(f),{recursive:true});await fs.writeFile(f,b);};
  const cfg=path.join(base,'config'),core=createPlatform({getProcesses:async()=>[]});
  const s=new DesktopService({dataDir:cfg,distRoot,core:{...core,discover:async()=>({games:[],warnings:[]})}});
  t.after(async()=>{await s.close();await fs.rm(base,{recursive:true,force:true});});
  await s.dispatch('select-game',{gameRoot:root});
  const host=dllHost(s,root),chat=dllTools(host).find(t=>t.name==='dll_pack_uninstall');
  const remove=async(id,confirm)=>(await chat.execute('test',{id},undefined,undefined,{hasUI:true,ui:{confirm}})).details;
  const consent={approved:true,source:'user'};
  const register=async d=>{const {planId}=await host('dll-pack-preview',{pack:d});await host('dll-pack-save',{planId},consent);};
  const shown=async()=> (await s.dllSnapshot(root,await core.inspectGame(root))).externalPacks.map(p=>p.id);
  await register({id:'skeeto'});assert.deepEqual(await shown(),[]);
  await put('bin/wininet.dll',peFixture(['SkeetoWininetProxyIdentity']));
  await put('skeeto.dll',peFixture(['necola_export','SkeetoBootstrapQuery']));
  await put('skeeto_setting.ini','custom=1');await put('left4dead2/skeeto/plugins/a.txt','user config');
  await put('VERSION.txt','another author');await put('left4dead2/addons/workshop/3787239937.vpk',zip({'SKEETO_WORKSHOP.txt':'SkeetoWorkshopPackage=1\n','VERSION.txt':'Skeeto 2.2.20'}));
  await put('left4dead2/addonlist.txt','"AddonList" { "workshop/3787239937.vpk" "1" // keep comment\n "mine.vpk" "1" }');
  assert.deepEqual(await shown(),['skeeto']);
  await s.packRegister.setEnabled(root,'skeeto',false,()=>core.inspectGame(root));
  const id='skeeto';
  assert.equal((await remove(id,async(_title,body)=>{assert.match(body,/matcha-off-/);assert.match(body,/skeeto_setting.ini/);assert.match(body,/3787239937/);return false;})).applied,false);
  const p=await s.packRemoval.preview(root,id);
  await put('skeeto_setting.ini','changed while reading');
  await assert.rejects(s.packRemoval.apply(root,p.planId,consent),{code:'pack_stale'});
  const inspect=s.core.inspectGame;s.core.inspectGame=async()=>({processes:[{pid:1}]});
  await assert.rejects(remove(id,async()=>true),{code:'game_running'});s.core.inspectGame=inspect;
  const result=await remove(id,async()=>true);assert.equal(result.status,'uninstalled');
  assert.deepEqual(result.removedPackages,['workshop/3787239937.vpk']);
  for(const r of ['skeeto.dll','skeeto_setting.ini','bin/wininet.dll','left4dead2/skeeto','left4dead2/addons/workshop/3787239937.vpk'])await assert.rejects(fs.access(path.join(root,r)),{code:'ENOENT'});
  assert.ok(!(await fs.readdir(path.join(root,'bin'))).some(n=>n.includes('matcha-off-')));
  assert.equal(await fs.readFile(path.join(root,'VERSION.txt'),'utf8'),'another author');
  assert.match(await fs.readFile(path.join(root,'left4dead2/addonlist.txt'),'utf8'),/keep comment\s+"mine.vpk" "1"/);
  assert.doesNotMatch(await fs.readFile(path.join(root,'left4dead2/addonlist.txt'),'utf8'),/3787239937/);
  assert.deepEqual(await s.packRegister.load(),[]);assert.deepEqual(await shown(),[]);

  const r='left4dead2/addons/example/bin/server.dll',bytes='example publisher',extra='left4dead2/addons/example/personal.txt';
  await put(r,bytes);await put(extra,'draft');
  await register({id:'example',name:'Example',source:'Fixture publisher',maintenance:'Local fixture',launch:'Source',files:[{role:'entry',path:r,sha256:createHash('sha256').update(bytes).digest('hex')}]});
  assert.equal((await remove('example',async()=>assert.fail('blocked plan prompted'))).status,'blocked');
  assert.equal(await fs.readFile(path.join(root,extra),'utf8'),'draft');await fs.unlink(path.join(root,extra));
  assert.equal((await remove('example',async()=>true)).status,'uninstalled');
  assert.deepEqual(await shown(),[]);await fs.access(path.join(root,'left4dead2.exe'));
});
