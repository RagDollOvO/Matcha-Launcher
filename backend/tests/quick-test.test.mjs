import { quickFixture } from './quick-test-fixtures.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import {parseKeyValues} from '../core.mjs';
const approval={approved:true,source:'user'};
const preset={modIds:['a_dir.vpk'],mapModId:'b.vpk',map:'custom_room',width:960,quiet:true,infiniteAmmo:true};
test('quick test: isolated split VPK, map, CFG, direct window arguments and observable readiness',async t=>{
  const base=await fs.mkdtemp(path.join(os.tmpdir(),'flare-quick-'));const f=await quickFixture(base);t.after(()=>f.service.close());
  const before=await fs.readFile(path.join(f.content,'addonlist.txt'));
  const options=await f.service.dispatch('test-options',{modIds:preset.modIds});
  assert.ok(!('suggestedWeapon' in options));assert.ok(options.maps.some(m=>m.id==='custom_room'&&m.modId==='b.vpk'));assert.ok(!options.maps.some(m=>m.id==='c1m1_hotel'));
  const result=await f.service.dispatch('start-test',{preset},approval);
  assert.equal(result.pid,777);assert.equal(f.launches.length,1);
  const args=f.launches[0].args;assert.ok(args.includes('-noborder'));assert.ok(args.includes('-insecure'));assert.ok(!args.includes('-vulkan'));assert.equal(args[args.indexOf('+map')+1],'custom_room');
  assert.equal(f.launches[0].file,path.join(result.directory,'left4dead2.exe'));
  assert.equal(f.launches[0].cwd,result.directory);
  assert.equal(args[args.indexOf('-game')+1],'left4dead2');
  const info=await fs.readFile(path.join(result.directory,'left4dead2/gameinfo.txt'),'utf8');
  assert.match(info,/GameBin/);assert.ok(!info.includes(f.content.replaceAll('\\','/')+'"'));
  assert.ok(info.indexOf('/mounts/mod-0')<info.indexOf('/mounts/mod-1'));
  assert.ok(info.indexOf('/mounts/mod-1')<info.indexOf('/left4dead2"'));
  assert.equal(await fs.readFile(path.join(result.directory,'update/gameinfo.txt'),'utf8'),info);
  const search=parseKeyValues(info).GameInfo.FileSystem.SearchPaths;
  assert.equal(search.MOD,path.join(result.directory,'flare').replaceAll('\\','/'));
  assert.equal(search.DEFAULT_WRITE_PATH,search.MOD);
  assert.equal(search.BASE_PATH,result.directory.replaceAll('\\','/'));
  assert.ok((await fs.stat(path.join(search.BASE_PATH,'left4dead2/pak01_dir.vpk'))).isFile());
  assert.equal(await fs.readFile(path.join(result.directory,'left4dead2/maps/c1m1_hotel.bsp'),'utf8'),'BASE_MAP');
  assert.ok((await fs.stat(path.join(result.directory,'mounts/mod-0/pak01_000.vpk'))).isFile());
  assert.ok((await fs.stat(path.join(result.directory,'mounts/mod-1/pak01_dir.vpk'))).isFile());
  assert.deepEqual(await fs.readdir(path.join(result.directory,'left4dead2/addons')),[]);
  assert.equal(await fs.readFile(path.join(result.directory,'flare/cfg/config.cfg'),'utf8'),'exec config_default.cfg\n');
  assert.doesNotMatch(await fs.readFile(path.join(result.directory,'flare/cfg/flare_test.cfg'),'utf8'),/\bgive\b|\bF6\b/);
  assert.doesNotMatch(await fs.readFile(path.join(result.directory,'flare/scripts/vscripts/flare_quicktest.nut'),'utf8'),/\bgive\b|\bgod\b/);
  assert.equal(await fs.readFile(path.join(f.content,'cfg/config.cfg'),'utf8'),'USER_CONFIG');
  assert.deepEqual(await fs.readFile(path.join(f.content,'addonlist.txt')),before);
  assert.equal((await f.service.dispatch('test-status')).state,'loading');
  assert.equal((await f.service.snapshot()).game.running,true);
  await fs.writeFile(path.join(result.directory,'flare/console.log'),`FLARE_TEST_CONFIG_${result.token}\nFLARE_TEST_READY_${result.token}\n`);
  assert.equal((await f.service.dispatch('test-status')).state,'ready');
  await assert.rejects(f.service.dispatch('start-test',{preset},approval),{code:'game_running'});
  f.setRunning([]);assert.equal((await f.service.dispatch('test-status')).state,'exited');
  assert.deepEqual((await f.service.dispatch('test-options')).preset,preset);
});
test('quick test: surface consistency rejection from legacy bin log and keep running guard',async t=>{
  const base=await fs.mkdtemp(path.join(os.tmpdir(),'flare-quick-failure-'));const f=await quickFixture(base);t.after(()=>f.service.close());
  const run=await f.service.dispatch('start-test',{preset},approval);
  const log=path.join(run.directory,'bin/console.log');
  await fs.writeFile(log,`FLARE_TEST_CONFIG_${run.token}\nServer is enforcing consistency for this file:\nFile left4dead2/pak01_dir.vpk was not found.\n`);
  let status=await f.service.dispatch('test-status');
  assert.equal(status.state,'failed');assert.equal(status.processRunning,true);assert.equal(status.logFile,log);
  assert.match(status.failure,/left4dead2\/pak01_dir.vpk/);
  f.setRunning([]);status=await f.service.dispatch('test-status');
  assert.equal(status.state,'failed');assert.equal(status.processRunning,false);
});
test('quick test: reuse private cache, reject stale readiness, refresh replaced VPK',async t=>{
  const base=await fs.mkdtemp(path.join(os.tmpdir(),'flare-quick-cache-'));const f=await quickFixture(base);t.after(()=>f.service.close());
  const first=await f.service.dispatch('start-test',{preset},approval);
  assert.equal(first.cacheHit,false);f.setRunning([]);
  await fs.writeFile(path.join(first.directory,'flare/modelsounds.cache'),'ENGINE_CACHE');
  await fs.writeFile(path.join(first.directory,'flare/console.log'),`FLARE_TEST_READY_${first.token}\n`);
  await fs.writeFile(path.join(first.directory,'flare/cfg/flare_test.cfg'),'bind F6 "give rifle"\n');
  await fs.writeFile(path.join(first.directory,'flare/cfg/config.cfg'),'bind "F6" "give rifle"\nbind "MOUSE1" "+attack"\n');
  const second=await f.service.dispatch('start-test',{preset:{...preset,width:1280,weapon:'rifle;quit'}},approval);
  assert.equal(second.cacheHit,true);assert.equal(second.directory,first.directory);assert.notEqual(second.token,first.token);
  assert.equal((await f.service.dispatch('test-status')).state,'loading');
  assert.equal(await fs.readFile(path.join(second.directory,'flare/modelsounds.cache'),'utf8'),'ENGINE_CACHE');
  assert.equal(await fs.readFile(path.join(second.directory,'flare/cfg/config.cfg'),'utf8'),'bind "MOUSE1" "+attack"\n');
  assert.ok(!('weapon' in (await f.service.dispatch('test-options')).preset));
  assert.match(await fs.readFile(path.join(second.directory,'flare/scripts/vscripts/flare_quicktest.nut'),'utf8'),new RegExp(second.token));
  f.setRunning([]);
  const source=path.join(f.content,'addons/a_dir.vpk');await fs.copyFile(source,source+'.new');await fs.rename(source+'.new',source);
  const third=await f.service.dispatch('start-test',{preset},approval);
  assert.equal(third.cacheHit,false);assert.notEqual(third.directory,second.directory);
});
test('quick test: approval, input validation, selected map packages, removed selections and startup failure',async t=>{
  const base=await fs.mkdtemp(path.join(os.tmpdir(),'flare-quick-'));const f=await quickFixture(base);t.after(()=>f.service.close());
  await assert.rejects(f.service.dispatch('start-test',{preset}),{code:'confirmation_required'});
  for(const change of [{map:'c1m1_hotel;quit'},{width:777},{map:'absent_map'},{modIds:['missing.vpk']}])await assert.rejects(f.service.dispatch('start-test',{preset:{...preset,...change}},approval));
  assert.equal(f.launches.length,0);
  const options=await f.service.dispatch('test-options',{modIds:['b.vpk']});assert.ok(options.maps.some(m=>m.id==='custom_room'&&m.modId==='b.vpk'));
  await assert.rejects(f.service.dispatch('start-test',{preset:{...preset,mapModId:'a_dir.vpk'}},approval),{code:'test_map_missing'});
  f.api.launchQuickTest=async()=>{throw Object.assign(new Error('Steam missing'),{code:'steam_missing'});};
  await assert.rejects(f.service.dispatch('start-test',{preset},approval),{code:'steam_missing'});
  assert.equal((await f.service.dispatch('test-status')).state,'idle');
  await fs.unlink(path.join(f.content,'addons/a_dir.vpk'));
  const stale=await f.service.dispatch('test-options');assert.deepEqual(stale.preset.modIds,['a_dir.vpk']);
});
