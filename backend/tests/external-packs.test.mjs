test('two installer layouts: verified files, root isolation, live record, stale confirmation and occupied entry',async(t)=>{
  const data=await fs.mkdtemp(path.join(os.tmpdir(),'matcha-pack-')),root=path.join(data,'game'),exe=path.join(root,'left4dead2.exe');
  const put=async(rel,bytes)=>{const p=path.join(root,rel);await fs.mkdir(path.dirname(p),{recursive:true});await fs.writeFile(p,bytes)};
  const inspection={processes:[]};
  const modules={path:exe,modules:[path.join(root,'skeeto.dll')]};
  const manager=new ExternalPlatforms({getModules:async()=>modules});
  const reg=new PackRegister(data,manager);
  const changed=[];
  const dir=path.join(data,'pi'),old=process.env.PI_CODING_AGENT_DIR;
  process.env.PI_CODING_AGENT_DIR=dir;t.after(()=>{if(old===undefined)delete process.env.PI_CODING_AGENT_DIR;else process.env.PI_CODING_AGENT_DIR=old;});
  const service={ready:Promise.resolve(),piConfigDir:dir,packRegister:reg,core:{inspectGame:async()=>inspection},requireRoot:async()=>root,serial:fn=>fn(),emit:(...e)=>changed.push(e)};
  const tools=dllTools(dllHost(service,root));
  const call=async(name,params,accept=true)=>(await tools.find(t=>t.name===name).execute('fixture',params,new AbortController().signal,undefined,{hasUI:true,ui:{confirm:async()=>accept}})).details;
  await put('bin/wininet.dll',peFixture(['Unrelated']));
  assert.equal((await call('dll_pack_check',{id:'skeeto'})).row.state,'occupied');
  await put('bin/wininet.dll',peFixture(['SkeetoWininetProxyIdentity']));
  assert.equal((await call('dll_pack_check',{id:'skeeto'})).row.state,'partial');
  await put('skeeto.dll',peFixture(['SkeetoBootstrapQuery','necola_export']));
  const ready=await call('dll_pack_check',{id:'skeeto'});assert.equal(ready.row.state,'installed');assert.equal(ready.row.runtime,'offline');
  assert.equal((await call('dll_pack_record',{planId:ready.planId},false)).applied,false);
  assert.deepEqual(await reg.load(),[]);
  await savePermissions(dir,{mode:'full'});
  await call('dll_pack_record',{planId:ready.planId},false);
  assert.equal((await reg.load()).length,1);
  inspection.processes=[{pid:1,path:exe}];const loaded=(await reg.list(root,inspection))[0];assert.equal(loaded.runtime,'loaded');
  assert.deepEqual(loaded.files.map(f=>f.mapped),[false,true]);
  modules.modules=[path.join(data,'elsewhere','skeeto.dll')];assert.equal((await reg.list(root,inspection))[0].runtime,'not-seen');
  inspection.processes=[];
  // Simulate a second author's documented Source 1 VDF layout. No server or installer is run.
  const vdf='"Plugin" { "file" "addons/metamod/bin/server" }',bin=Buffer.from('stable release fixture');
  const pack={id:'metamod',name:'Metamod:Source',source:'https://wiki.alliedmods.net/Installing_Metamod%3ASource',launch:'本地服务器启动',
    maintenance:'按发行包清单维护',files:[['left4dead2/addons/metamod.vdf','entry',vdf],['left4dead2/addons/metamod/bin/server.dll','module',bin]]
      .map(([path,role,bytes])=>({path,role,sha256:createHash('sha256').update(bytes).digest('hex')}))};
  const before=await call('dll_pack_check',pack);assert.equal(before.row.state,'absent');
  await put(pack.files[0].path,vdf); await put(pack.files[1].path,bin);
  await assert.rejects(call('dll_pack_record',{planId:before.planId}),{code:'pack_stale'});
  const after=await call('dll_pack_check',pack);
  assert.equal((await call('dll_pack_record',{planId:after.planId})).lastCheck.state,'installed');
  const reopened=new PackRegister(data,manager);
  assert.equal((await reopened.preview(root,inspection,{id:'metamod'})).row.state,'installed');
  assert.equal((await reopened.list(data,inspection)).length,1);
  const conflict=await call('dll_pack_check',{...pack,id:'other'});assert.equal(conflict.row.conflicts[0].other,pack.name);
  await fs.writeFile(path.join(root,pack.files[0].path),'foreign');assert.equal((await call('dll_pack_check',{id:'metamod'})).row.state,'occupied');
  assert.equal(changed.length,2);
});

