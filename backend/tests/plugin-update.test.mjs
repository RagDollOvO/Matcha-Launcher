import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { createPlatform } from '../core.mjs';
import { createFixture, pluginFixture } from './fixtures.mjs';
const confirmation = { approved: true, source: 'user' };
test('plugin update preserves config, enabled state and old package; interrupted replacement restores ownership', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'flare-update-'));
  t.after(async () => { assert.equal(path.dirname(root), os.tmpdir()); assert.ok(path.basename(root).startsWith('flare-update-')); await fs.rm(root, { recursive: true, force: true }); });
  const f = await createFixture(root); let running = [];
  const core = createPlatform({ getProcesses: async () => running });
  await core.applyInstall(await core.planInstall(f), { confirmation });
  const bundled = await pluginFixture(path.join(root, 'bundled-update'), 'demo.hello');
  const bundledManifest = JSON.parse(await fs.readFile(path.join(bundled, 'manifest.json')));
  bundledManifest.version = '0.2.0'; await fs.writeFile(path.join(bundled, 'manifest.json'), JSON.stringify(bundledManifest));
  assert.equal((await core.updatePlugin({ gameRoot: f.gameRoot, pluginDirectory: bundled, confirmation })).enabled, true);
  const candidate = await pluginFixture(path.join(root, 'candidate'), 'test.upgrade');
  await core.installPlugin({ gameRoot: f.gameRoot, pluginDirectory: candidate, confirmation });
  await core.setPluginEnabled({ gameRoot: f.gameRoot, pluginId: 'test.upgrade', enabled: true, confirmation });
  const dest = path.join(f.runtime, 'plugins/test.upgrade'), config = '{"greeting":"我的设置"}\n';
  await fs.writeFile(path.join(dest, 'config.json'), config);
  await fs.writeFile(path.join(dest, 'old-source.txt'), 'old source and custom file');
  const m = JSON.parse(await fs.readFile(path.join(candidate, 'manifest.json'))); m.version = '0.2.0';
  await fs.writeFile(path.join(candidate, 'manifest.json'), JSON.stringify(m));
  await assert.rejects(core.updatePlugin({ gameRoot: f.gameRoot, pluginDirectory: candidate }), { code: 'confirmation_required' });
  running = [{ pid: 12, name: 'left4dead2' }];
  await assert.rejects(core.updatePlugin({ gameRoot: f.gameRoot, pluginDirectory: candidate, confirmation }), { code: 'game_running' });
  running = [];
  const updated = await core.updatePlugin({ gameRoot: f.gameRoot, pluginDirectory: candidate, confirmation });
  assert.equal(updated.enabled, true);
  assert.equal(await fs.readFile(path.join(dest, 'config.json'), 'utf8'), config);
  assert.equal(await fs.readFile(path.join(updated.previousDirectory, 'old-source.txt'), 'utf8'), 'old source and custom file');
  assert.equal((await core.listPlugins(f.gameRoot)).find(p => p.manifest.id === 'test.upgrade').manifest.version, '0.2.0');
  assert.equal((await core.listPlugins(f.gameRoot, { includeConfig: true })).find(p => p.manifest.id === 'test.upgrade').savedConfig.greeting, '我的设置');
  assert.equal((await core.listPlugins(f.gameRoot)).find(p => p.manifest.id === 'test.upgrade').savedConfig, undefined);
  m.config[0].type = 'integer'; m.config[0].default = 1; delete m.config[0].maxLength;
  await fs.writeFile(path.join(candidate, 'manifest.json'), JSON.stringify(m));
  await assert.rejects(core.updatePlugin({ gameRoot: f.gameRoot, pluginDirectory: candidate, confirmation }), { code: 'invalid_parameter' });
  const statePath = path.join(f.runtime, 'platform-state.json'), state = JSON.parse(await fs.readFile(statePath));
  const id = randomUUID(), backup = `.plugin-backup-${id}`, stage = `.plugin-stage-${id}`;
  state.pluginTransaction = { kind: 'update', id, pluginId: 'test.upgrade', stage, backup, previous: state.plugins['test.upgrade'], previousMarker: JSON.parse(await fs.readFile(path.join(dest, '.l4p-package.json'))) };
  await fs.writeFile(statePath, JSON.stringify(state));
  await fs.rename(dest, path.join(f.runtime, backup));
  await fs.mkdir(dest); await fs.writeFile(path.join(dest, '.l4p-package.json'), JSON.stringify({ platform: 'l4p', transactionId: id, pluginId: 'test.upgrade' }));
  await fs.mkdir(path.join(f.runtime, stage));
  await core.recover(f.gameRoot, { confirmation });
  assert.equal(await fs.readFile(path.join(dest, 'config.json'), 'utf8'), config);
  assert.equal((await core.listPlugins(f.gameRoot)).find(p => p.manifest.id === 'test.upgrade').enabled, true);
  assert.equal(JSON.parse(await fs.readFile(statePath)).pluginTransaction, undefined);
});
