export function idleLine(sources: SupportSource[]) {
  const set = new Set(sources);
  return pick(set.size === 1 ? [...GENERAL, ...BY_SOURCE[sources[0]], ...BY_SOURCE[sources[0]]] : GENERAL);
}
/** 连着「下次一定」越多，越委屈 */
export function teaseLine(n: number) {
  if (n >= 10) return `已经「下次一定」${n} 回了……作者哭成水龙头了 (ㄒoㄒ)`;
  if (n >= 6) return `第 ${n} 次「下次一定」，作者的小本本上都记着呢 (｀・ω・´)`;
  if (n >= 3) return `这已经是第 ${n} 次「下次一定」了…… (´；ω；｀)`;
  return '';
}
export const likedLine = (n: number) => `你已经点过 ${n} 个赞啦，好人一生平安 ♡`;
